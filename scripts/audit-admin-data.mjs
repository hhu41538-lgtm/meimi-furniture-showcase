const codes = [];
const counters = {};
const allItems = [
  ...[...productsSource.matchAll(/name:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"/g)].map((match) => ({ name: match[1], category: match[2], type: "product" })),
  ...[...studioSource.matchAll(/name:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"/g)].map((match) => ({ name: match[1], category: match[2], type: "studio" })),
];

function prefixFor(item) {
  const normalized = `${item.category} ${item.name}`.toLowerCase();
  if (normalized.includes("coffee")) return "CT";
  if (normalized.includes("chair")) return "AC";
  if (normalized.includes("bed")) return "BD";
  if (normalized.includes("cabinet")) return "CB";
  const map = { sofa: "SF", dining: "DT", mattress: "MT", outdoor: "OD", studio: "ST" };
  return map[item.category] ?? (item.type === "studio" ? "ST" : "PR");
}

for (const item of allItems) {
  const prefix = prefixFor(item);
  counters[prefix] = (counters[prefix] ?? 0) + 1;
  codes.push(`MH-${prefix}-${String(counters[prefix]).padStart(3, "0")}`);
}

const duplicateCodes = codes.filter((code, index) => codes.indexOf(code) !== index);
const invalidCodes = codes.filter((code) => !/^MH-[A-Z]{2}-\d{3}$/.test(code));
if (duplicateCodes.length) failures.push(`Duplicate generated product codes: ${[...new Set(duplicateCodes)].join(", ")}`);
if (invalidCodes.length) failures.push(`Invalid generated product codes: ${invalidCodes.join(", ")}`);
if (codes.length !== productSlugs.length + studioSlugs.length) {
  failures.push(`Generated ${codes.length} codes for ${productSlugs.length + studioSlugs.length} catalogue entries`);
}

if (failures.length) {
  console.error("Admin data audit failed:");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exitCode = 1;
} else {
  console.log(`Admin data audit passed (${productSlugs.length} products, ${studioSlugs.length} studio items, ${codes.length} codes).`);
}
